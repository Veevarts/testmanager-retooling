-- TC-158 AC1: mecanismo de las 4 fechas 2026 — reservas con ARRIVALDATE ese dia
-- vs sales orders TRANSACTIONDATE ese dia (esperado: >=1 reserva, 0 sales orders)
SELECT CAST(r.ARRIVALDATE AS DATE) AS TheDate, COUNT(*) AS ReservationsThatDay
FROM RESERVATION r
WHERE CAST(r.ARRIVALDATE AS DATE) IN ('2026-07-03', '2026-08-07', '2026-08-20', '2026-08-21')
GROUP BY CAST(r.ARRIVALDATE AS DATE);

SELECT CAST(so.TRANSACTIONDATE AS DATE) AS TheDate, COUNT(*) AS SalesOrdersThatDay
FROM SALESORDER so
WHERE CAST(so.TRANSACTIONDATE AS DATE) IN ('2026-07-03', '2026-08-07', '2026-08-20', '2026-08-21')
GROUP BY CAST(so.TRANSACTIONDATE AS DATE);
